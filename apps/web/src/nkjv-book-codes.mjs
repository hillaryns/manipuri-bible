function normalizeBookName(name) {
  return name
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[.]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

export function getNkjvBookCode(bookName) {
  return BOOK_CODES[normalizeBookName(bookName)] ?? null;
}
